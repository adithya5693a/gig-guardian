const LanguageContext = createContext<{
  language: Language;
  setLanguage: (language: Language) => void;
  t: (key: TranslationKey) => string;
} | null>(null);

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [language, setLanguage] = useState<Language>(() =>
    typeof window !== "undefined"
      ? (window.localStorage.getItem("gigshield-language") as Language) || "en"
      : "en",
  );
  useEffect(() => window.localStorage.setItem("gigshield-language", language), [language]);
  const value = useMemo(
    () => ({ language, setLanguage, t: (key: TranslationKey) => translations[language][key] }),
    [language],
  );
  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useI18n() {
  const value = useContext(LanguageContext);
  if (!value) throw new Error("useI18n must be used inside LanguageProvider");
  return {
    ...value,
    translate: (text: string) =>
      extraTranslations[value.language]?.[text] ??
      dashboardTranslations[value.language][text] ??
      text,
  };
}
